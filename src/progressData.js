export function currentPassLevel(passClicks) {
  const clicks = passClicks || 0;
  let lvl = 0;
  for (let i = 1; i <= PASS_MAX_LEVEL; i++) {
    if (clicks >= PASS_LEVEL_THRESHOLDS[i]) lvl = i;
    else break;
  }
  return lvl;
}


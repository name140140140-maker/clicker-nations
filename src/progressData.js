/* Нагорода рівня: { type: "points", amount } | { type: "title"|"icon"|"banner", id } | null */
export function passReward(track, level) {
  const pair = PASS_REWARD_TABLE[level];
  if (!pair) return null;
  const [kind, v] = pair[track === "premium" ? 1 : 0];
  if (kind === "p") return { type: "points", amount: v };
  if (kind === "t") return { type: "title", id: PASS_TITLE_IDS[v] };
  if (kind === "a") return { type: "icon", id: PASS_ICON_IDS[v] };
  return { type: "banner", id: PASS_BANNER_IDS[v] };
}


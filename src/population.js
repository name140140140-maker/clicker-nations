const BASE = {};
for (const [c, k, g] of REAL) BASE[c] = { pop: k * 1000, g };

const REF_DAY = Math.floor(Date.UTC(2026, 6, 1) / 864e5);
export const dayNumber = (now = Date.now()) => Math.floor(now / 864e5);

/* Детермінований «шум» 0..1 за кодом країни й днем */
function noise(code, day) {
  let h = 2166136261 ^ day;
  for (let i = 0; i < code.length; i++) h = Math.imul(h ^ code.charCodeAt(i), 16777619);
  h ^= h >>> 15;
  h = Math.imul(h, 2246822507);
  h ^= h >>> 13;
  return ((h >>> 0) % 10000) / 10000;
}

const cache = new Map();
/* Населення країни-засновника на кінець вказаного дня (ціле число) */
export function realPopulation(code, day = dayNumber()) {
  const b = BASE[code];
  if (!b) return 0;
  const d = Math.max(REF_DAY, day);
  let hit = cache.get(code);
  if (!hit || hit.day > d || hit.v !== stateVersion()) hit = { day: REF_DAY, pop: b.pop };
  let { day: cur, pop } = hit;
  while (cur < d) {
    cur += 1;
    pop += (pop * b.g) / 36500 * (0.4 + 1.2 * noise(code, cur)); // середнє множника = 1
    pop += pop * eventRate(code, cur); // події світу: пандемія, землетрус, санкції, революція
  }
  cache.set(code, { day: cur, pop, v: stateVersion() });
  return Math.round(pop);
}
/* Зміна за добу (сьогодні мінус учора) */
export function dailyChange(code, day = dayNumber()) {
  return realPopulation(code, day) - realPopulation(code, day - 1);
}

export const hasRealPopulation = (code) => !!BASE[code];

/* Повне число з пробілами: 37 912 345 */
export const fmtPop = (n) => (n ? Math.round(n).toLocaleString("uk-UA").replace(/ /g, " ") : "—");
export const fmtDelta = (n) => (n === 0 ? "0" : (n > 0 ? "+" : "−") + Math.abs(Math.round(n)).toLocaleString("uk-UA").replace(/ /g, " "));

/* Населення поточних власників: { [код]: [населення, зміна за добу] }.
   Місто несе частку населення країни-засновника (за базовим володінням областей), тож загальна сума світу
   дорівнює реальному населенню, а захоплення міста переносить людей до переможця. */
export async function computeNationPops(nations) {
  const [cities, ro] = await Promise.all([loadCities(), loadRegionOwners()]);
  const out = {};
  if (!cities?.list?.length || !ro) return out;
  const co = nations?.cityOwners || {};
  const owners = nations?.owners || {};
  const sumP = {};
  for (const c of cities.list) {
    const o = ro.r[c.rid];
    if (o) sumP[o] = (sumP[o] || 0) + (c.p || 0);
  }
  const day = dayNumber();
  const scale = {};
  const dscale = {};
  for (const code of Object.keys(sumP)) {
    if (!sumP[code]) continue;
    scale[code] = realPopulation(code, day) / sumP[code];
    dscale[code] = dailyChange(code, day) / sumP[code];
  }
  for (const c of cities.list) {
    const base = ro.r[c.rid];
    const holder = co[cityKey(c)] || owners[c.rid];
    if (!base || !holder || !scale[base]) continue;
    const row = out[holder] || (out[holder] = [0, 0]);
    row[0] += (c.p || 0) * scale[base];
    row[1] += (c.p || 0) * dscale[base];
  }
  return out;
}
